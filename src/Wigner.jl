"""
Partial Wigner-d / D rotation of spherical-harmonic coefficients.

`Δ^ℓ_{mn} = d^ℓ_{mn}(π/2)` is generated by the Trapani–Navaza recurrence
(Trapani & Navaza, Acta Cryst. A62, 262, 2006). Arbitrary-angle small-d uses

    d^ℓ_{mn}(β) = i^{m-n} Σ_k Δ^ℓ_{km} Δ^ℓ_{kn} exp(-i k β)

and ZYZ Euler D-matrices are `D_{m'm}(α,β,γ) = e^{-im'α} d_{m'm}(β) e^{-imγ}`.

Only rows `|m'| ≤ mmax` are produced (partial rotation).
"""

"""
    wigner_d(ℓ, m, n, β)

Wigner small-d `d^ℓ_{mn}(β)` via the log-gamma explicit sum (stability for moderate `ℓ`).
"""
function wigner_d(ℓ::Integer, m::Integer, n::Integer, β::Real)
    T = float(typeof(float(β)))
    (abs(m) > ℓ || abs(n) > ℓ) && return zero(T)
    c = cos(T(β) / 2)
    s = sin(T(β) / 2)
    # Edmonds / Wikipedia: d^ℓ_{m n}(β), s from max(0, n-m) to min(ℓ+n, ℓ-m),
    # sign (-1)^{m-n+s}.
    kmin = max(0, n - m)
    kmax = min(ℓ + n, ℓ - m)
    pref = (SpecialFunctions.loggamma(T(ℓ + m + 1)) + SpecialFunctions.loggamma(T(ℓ - m + 1)) +
            SpecialFunctions.loggamma(T(ℓ + n + 1)) + SpecialFunctions.loggamma(T(ℓ - n + 1))) / 2
    tot = zero(T)
    for k in kmin:kmax
        den = (SpecialFunctions.loggamma(T(ℓ + n - k + 1)) + SpecialFunctions.loggamma(T(k + 1)) +
               SpecialFunctions.loggamma(T(ℓ - m - k + 1)) + SpecialFunctions.loggamma(T(k + m - n + 1)))
        sgn = iseven(k + m - n) ? one(T) : -one(T)
        tot += sgn * exp(pref - den) * (c^(2ℓ + n - m - 2k)) * (s^(2k + m - n))
    end
    return tot
end

@inline function _im_pow(::Type{CT}, k::Integer) where {CT}
    r = mod(Int(k), 4)
    return r == 0 ? CT(1, 0) : r == 1 ? CT(0, 1) : r == 2 ? CT(-1, 0) : CT(0, -1)
end

@inline _Nℓ(::Type{T}, ℓ::Integer) where {T} = sqrt(T(2ℓ + 1) / (4 * T(π)))
@inline _Nℓ(ℓ::Integer) = _Nℓ(Float64, ℓ)

@inline _rot_get(alm, ℓ, m, lmax, b, spin::Integer) =
    spin == 0 ? _coeff(alm, ℓ, m, b) : _spin_coeff(alm, ℓ, m, lmax, b)

@inline function _rot_set!(out, ℓ, m, lmax, b, val, spin::Integer)
    return spin == 0 ? _coeff_set!(out, ℓ, m, b, val) : _spin_coeff_set!(out, ℓ, m, lmax, b, val)
end

"""
    _wigner_d_halfpi_step!(dl, dlp, ℓ, off)

Trapani–Navaza step: fill `Δ^ℓ` in `dl` from `Δ^{ℓ-1}` in `dlp`. Matrices are
indexed with offset `off = lmax+1` so `dl[m+off, n+off] = Δ^ℓ_{mn}`.
"""
function _wigner_d_halfpi_step!(dl::AbstractMatrix{T}, dlp::AbstractMatrix{T},
                                ℓ::Integer, off::Integer) where {T}
    if ℓ == 0
        dl[off, off] = one(T)
        return dl
    end
    # Trapani–Navaza (2006) eqs. 9–11 as in s2fft: `dl[m+off, n+off] = d^ℓ_{m n}(π/2)`.
    # Last *row* m = ℓ is filled from Δ^{ℓ-1}, then m decreases (first index).
    @inbounds begin
        dl[ℓ + off, off] = -sqrt(T(2ℓ - 1) / T(2ℓ)) * dlp[(ℓ - 1) + off, off]
        for n in 1:ℓ
            dl[ℓ + off, n + off] =
                sqrt(T(ℓ) * T(2ℓ - 1) / (T(2) * T(ℓ + n) * T(ℓ + n - 1))) *
                dlp[(ℓ - 1) + off, (n - 1) + off]
        end
        denℓ = sqrt(T(2ℓ))
        for n in 0:ℓ
            dl[(ℓ - 1) + off, n + off] = (T(2) * T(n) / denℓ) * dl[ℓ + off, n + off]
        end
        for m in (ℓ - 2):-1:0
            c1 = T(2) / sqrt(T(ℓ - m) * T(ℓ + m + 1))
            s2 = sqrt(T(ℓ - m - 1) * T(ℓ + m + 2) / (T(ℓ - m) * T(ℓ + m + 1)))
            for n in 0:ℓ
                dl[m + off, n + off] =
                    c1 * T(n) * dl[(m + 1) + off, n + off] - s2 * dl[(m + 2) + off, n + off]
            end
        end
        for n in 0:ℓ, m in -ℓ:-1
            dl[m + off, n + off] = (iseven(ℓ + n) ? one(T) : -one(T)) * dl[(-m) + off, n + off]
        end
        for m in -ℓ:ℓ
            sgn = iseven(ℓ + abs(m)) ? one(T) : -one(T)
            for n in -ℓ:-1
                dl[m + off, n + off] = sgn * dl[m + off, (-n) + off]
            end
        end
    end
    return dl
end

# Packed Δ^ℓ when it fits (Trapani fallback apply). Thin d(β) is packed while it
# fits; otherwise apply streams an ℓ-recurrence of d(β) with three planes.
const _WIGNER_Δ_CACHE_BYTES = 256 * 1024 * 1024
# Real d^ℓ_{m'm}(β) for |m'|≤mmax. ~1 GB at L=512, M=271; stream three planes at L=1024.
const _WIGNER_THIN_D_BYTES = 1536 * 1024 * 1024

function _wigner_Δ_cache_nbytes(lmax::Integer, ::Type{T}) where {T}
    n = 0
    for ℓ in 0:Int(lmax)
        d = 2ℓ + 1
        n += d * d
    end
    return n * sizeof(T)
end

function _thin_d_cache_nbytes(lmax::Integer, mmax::Integer, ::Type{T}) where {T}
    n = 0
    M = Int(mmax)
    for ℓ in 0:Int(lmax)
        mlim = min(ℓ, M)
        n += (2mlim + 1) * (2ℓ + 1)
    end
    return n * sizeof(T)
end

"""
Packed `Δ^ℓ_{mn} = d^ℓ_{mn}(π/2)` planes, one contiguous `(2ℓ+1)×(2ℓ+1)` matrix per degree.
Empty if the packed size would exceed `_WIGNER_Δ_CACHE_BYTES`.
"""
function wigner_Δ_cache(::Type{T}, lmax::Integer) where {T}
    L = Int(lmax)
    if L < 0 || _wigner_Δ_cache_nbytes(L, T) > _WIGNER_Δ_CACHE_BYTES
        return Matrix{T}[]
    end
    planes = Vector{Matrix{T}}(undef, L + 1)
    Lw = 2L + 1
    dl = zeros(T, Lw, Lw)
    dlp = zeros(T, Lw, Lw)
    off = L + 1
    _wigner_d_halfpi_step!(dl, dlp, 0, off)
    planes[1] = T[one(T);;]
    for ℓ in 1:L
        dl, dlp = dlp, dl
        _wigner_d_halfpi_step!(dl, dlp, ℓ, off)
        planes[ℓ + 1] = Matrix{T}(view(dl, (off - ℓ):(off + ℓ), (off - ℓ):(off + ℓ)))
    end
    return planes
end

"""
Thin real Wigner small-d at a fixed `β`: `planes[ℓ+1]` is `(2min(ℓ,mmax)+1)×(2ℓ+1)`
with rows `m' = -mlim:mlim` and columns `m = -ℓ:ℓ`. Empty `planes` if the packed
size would exceed `_WIGNER_THIN_D_BYTES`; apply then streams an `ℓ`-recurrence into
`rec1/rec2/rec3` (three `(2mmax+1)×(2lmax+1)` planes).
"""
struct WignerThinD{T}
    lmax::Int
    mmax::Int
    β::T
    planes::Vector{Matrix{T}}
    rec1::Matrix{T}
    rec2::Matrix{T}
    rec3::Matrix{T}
end

WignerThinD{T}() where {T} = WignerThinD{T}(-1, 0, zero(T), Matrix{T}[],
                                            zeros(T, 0, 0), zeros(T, 0, 0), zeros(T, 0, 0))

@inline function _thin_plane_view(P::AbstractMatrix, ℓ::Integer, mmax::Integer, lmax::Integer)
    mlim = min(Int(ℓ), Int(mmax))
    off_r = min(Int(lmax), Int(mmax)) + 1
    off_c = Int(lmax) + 1
    return view(P, (off_r - mlim):(off_r + mlim), (off_c - Int(ℓ)):(off_c + Int(ℓ)))
end

@inline function _d_get(P::AbstractMatrix{T}, mp::Integer, m::Integer, ℓ::Integer) where {T}
    mlim = (size(P, 1) - 1) ÷ 2
    (abs(mp) > mlim || abs(m) > ℓ) && return zero(T)
    return P[mp + mlim + 1, m + ℓ + 1]
end

function _wigner_d_fill_l1!(P::AbstractMatrix{T}, β::T) where {T}
    c = cos(β)
    s = sin(β)
    mlim = (size(P, 1) - 1) ÷ 2
    s2 = s / sqrt(T(2))
    fill!(P, zero(T))
    @inbounds for (mp, m, v) in ((1, 1, (1 + c) / 2),
                                 (1, 0, -s2),
                                 (1, -1, (1 - c) / 2),
                                 (0, 1, s2),
                                 (0, 0, c),
                                 (0, -1, -s2),
                                 (-1, 1, (1 - c) / 2),
                                 (-1, 0, s2),
                                 (-1, -1, (1 + c) / 2))
        abs(mp) <= mlim && (P[mp + mlim + 1, m + 2] = v)
    end
    return P
end

function _seed_hw_column!(P::AbstractMatrix{T}, ℓ::Int, n::Int, β::T) where {T}
    mlim = (size(P, 1) - 1) ÷ 2
    return _seed_hw_column!(P, ℓ, n, β, mlim, n + ℓ + 1, mlim + 1)
end

function _seed_hw_column!(P::AbstractMatrix{T}, ℓ::Int, n::Int, β::T,
                          mlim::Int, col::Int, row0::Int) where {T}
    c = cos(β / 2)
    s = sin(β / 2)
    tiny = sqrt(eps(T))
    if abs(c) <= tiny && abs(s) <= tiny
        return P
    end
    if abs(c) <= tiny
        target = n > 0 ? -ℓ : ℓ
        @inbounds for mp in -mlim:mlim
            P[mp + row0, col] = mp == target ? (iseven(ℓ + mp) ? one(T) : -one(T)) : zero(T)
        end
        return P
    end
    if abs(s) <= tiny
        target = n
        @inbounds for mp in -mlim:mlim
            P[mp + row0, col] = mp == target ? one(T) : zero(T)
        end
        return P
    end
    mp0 = -mlim
    ac, as_ = abs(c), abs(s)
    lg = (SpecialFunctions.loggamma(T(2ℓ + 1)) - SpecialFunctions.loggamma(T(ℓ + mp0 + 1)) -
          SpecialFunctions.loggamma(T(ℓ - mp0 + 1))) / 2
    if n > 0
        lg += T(ℓ + mp0) * log(ac) + T(ℓ - mp0) * log(as_)
    else
        lg += T(ℓ - mp0) * log(ac) + T(ℓ + mp0) * log(as_)
    end
    @inbounds for mp in -mlim:mlim
        sgn = one(T)
        if n > 0
            s < 0 && isodd(ℓ - mp) && (sgn = -one(T))
            c < 0 && isodd(ℓ + mp) && (sgn = -sgn)
        else
            s < 0 && isodd(ℓ + mp) && (sgn = -one(T))
            c < 0 && isodd(ℓ - mp) && (sgn = -sgn)
            isodd(ℓ - mp) && (sgn = -sgn)
        end
        P[mp + row0, col] = sgn * exp(lg)
        mp == mlim && break
        lg += log(T(ℓ - mp) / T(ℓ + mp + 1)) / 2
        lg += n > 0 ? log(ac / as_) : log(as_ / ac)
    end
    return P
end

"""
Fill `Pnext = d^{ℓ+1}(β)` from `Pcur = d^ℓ` and `Pprev = d^{ℓ-1}` (`ℓ ≥ 1`).
Planes use the compact thin layout of [`WignerThinD`](@ref). Inner loop is over
contiguous `m'` rows so the `O(ℓ mmax)` step vectorizes. Optional `scratch` is
`(sLm, invsL1, mpv)` reused across degrees.
"""
function _wigner_d_advance!(Pnext::AbstractMatrix{T}, Pcur::AbstractMatrix{T},
                            Pprev::AbstractMatrix{T}, ℓ::Integer, β::T,
                            scratch::Union{Nothing, NTuple{3, Vector{T}}} = nothing) where {T}
    L = Int(ℓ)
    L1 = L + 1
    mlim_n = (size(Pnext, 1) - 1) ÷ 2
    mlim_c = (size(Pcur, 1) - 1) ÷ 2
    mlim_p = (size(Pprev, 1) - 1) ÷ 2
    fill!(Pnext, zero(T)) # leftover: extra |m'|=ℓ+1 rows when the thin plane grows
    mp_hi = min(L, mlim_n, mlim_c)
    mp_hi < 0 && return _seed_hw_and_rows!(Pnext, L1, mlim_n, β)
    twoLp1 = T(2L + 1)
    LT = T(L)
    L1T = T(L1)
    Lcβ = LT * L1T * cos(β)
    i0 = -mp_hi + mlim_n + 1
    i1 = mp_hi + mlim_n + 1
    drow = mlim_c - mlim_n
    prow = mlim_p - mlim_n
    mp_hi_p = min(L - 1, mlim_p, mp_hi)
    i0p = -mp_hi_p + mlim_n + 1
    i1p = mp_hi_p + mlim_n + 1
    nrows = size(Pnext, 1)
    sLm, invsL1, mpv = _advance_scratch(T, nrows, scratch)
    @inbounds for i in i0:i1
        mp = i - mlim_n - 1
        sLm[i] = sqrt(max(zero(T), T(L * L - mp * mp)))
        invsL1[i] = inv(sqrt(T(L1 * L1 - mp * mp)))
        mpv[i] = T(mp)
    end
    aligned = drow == 0 && prow == 0
    @inbounds for m in -(L - 1):(L - 1)
        jc = m + L1 + 1
        jcc = m + L + 1
        jcp = m + L
        sm = sqrt(T(L1 * L1 - m * m))
        sm1 = sqrt(T(L * L - m * m))
        invdenm = inv(LT * sm)
        c1 = twoLp1 * invdenm
        c0 = c1 * Lcβ
        c2 = L1T * sm1 * invdenm
        if aligned
            @simd ivdep for i in i0p:i1p
                Pnext[i, jc] = ((c0 - c1 * mpv[i] * T(m)) * Pcur[i, jcc] -
                                c2 * sLm[i] * Pprev[i, jcp]) * invsL1[i]
            end
        else
            @simd ivdep for i in i0p:i1p
                Pnext[i, jc] = ((c0 - c1 * mpv[i] * T(m)) * Pcur[i + drow, jcc] -
                                c2 * sLm[i] * Pprev[i + prow, jcp]) * invsL1[i]
            end
            for i in i0:(i0p - 1)
                Pnext[i, jc] = twoLp1 * (Lcβ - mpv[i] * T(m)) * Pcur[i + drow, jcc] * invdenm * invsL1[i]
            end
            for i in (i1p + 1):i1
                Pnext[i, jc] = twoLp1 * (Lcβ - mpv[i] * T(m)) * Pcur[i + drow, jcc] * invdenm * invsL1[i]
            end
        end
    end
    @inbounds for m in (-L, L)
        jc = m + L1 + 1
        jcc = m + L + 1
        invdenm = inv(LT * sqrt(T(L1 * L1 - m * m)))
        if aligned
            @simd ivdep for i in i0:i1
                Pnext[i, jc] = twoLp1 * (Lcβ - mpv[i] * T(m)) * Pcur[i, jcc] * invdenm * invsL1[i]
            end
        else
            @simd ivdep for i in i0:i1
                Pnext[i, jc] = twoLp1 * (Lcβ - mpv[i] * T(m)) * Pcur[i + drow, jcc] * invdenm * invsL1[i]
            end
        end
    end
    return _seed_hw_and_rows!(Pnext, L1, mlim_n, β)
end

function _wigner_fill_m_col!(Pnext::Matrix{T}, Pcur::Matrix{T}, Pprev::Matrix{T},
                             m::Int, L::Int, L1::Int, twoLp1::T, LT::T, L1T::T, Lcβ::T,
                             i0::Int, i1::Int, i0p::Int, i1p::Int,
                             sLm::Vector{T}, invsL1::Vector{T}, mpv::Vector{T},
                             off_c::Int) where {T}
    j = m + off_c
    Tm = T(m)
    sm = sqrt(T(L1 * L1 - m * m))
    sm1 = sqrt(T(L * L - m * m))
    invdenm = inv(LT * sm)
    c1 = twoLp1 * invdenm
    c0 = c1 * Lcβ
    c2 = L1T * sm1 * invdenm
    @inbounds begin
        @simd ivdep for i in i0p:i1p
            Pnext[i, j] = ((c0 - c1 * mpv[i] * Tm) * Pcur[i, j] -
                            c2 * sLm[i] * Pprev[i, j]) * invsL1[i]
        end
        for i in i0:(i0p - 1)
            Pnext[i, j] = twoLp1 * (Lcβ - mpv[i] * Tm) * Pcur[i, j] * invdenm * invsL1[i]
        end
        for i in (i1p + 1):i1
            Pnext[i, j] = twoLp1 * (Lcβ - mpv[i] * Tm) * Pcur[i, j] * invdenm * invsL1[i]
        end
    end
    return nothing
end

"""
Advance `d^{ℓ+1}` in the packed stream buffers (all `(2mmax+1)×(2lmax+1)`,
column `m` at `m + lmax + 1`). Dense `Matrix` indexing, not `SubArray` views.
"""
function _wigner_d_advance_buf!(Pnext::Matrix{T}, Pcur::Matrix{T}, Pprev::Matrix{T},
                                ℓ::Integer, mmax::Integer, lmax::Integer, β::T,
                                scratch::NTuple{3, Vector{T}}) where {T}
    L = Int(ℓ)
    L1 = L + 1
    M = Int(mmax)
    off_r = min(Int(lmax), M) + 1
    off_c = Int(lmax) + 1
    mlim_n = min(L1, M)
    mlim_c = min(L, M)
    mlim_p = min(L - 1, M)
    mp_hi = min(L, mlim_n, mlim_c)
    mp_hi < 0 && return _seed_hw_buf!(Pnext, L1, mlim_n, β, off_r, off_c)
    twoLp1 = T(2L + 1)
    LT = T(L)
    L1T = T(L1)
    Lcβ = LT * L1T * cos(β)
    mp_hi_p = min(L - 1, mlim_p, mp_hi)
    i0 = -mp_hi + off_r
    i1 = mp_hi + off_r
    i0p = -mp_hi_p + off_r
    i1p = mp_hi_p + off_r
    sLm, invsL1, mpv = scratch
    @inbounds for i in i0:i1
        mp = i - off_r
        sLm[i] = sqrt(max(zero(T), T(L * L - mp * mp)))
        invsL1[i] = inv(sqrt(T(L1 * L1 - mp * mp)))
        mpv[i] = T(mp)
    end
    if Threads.nthreads() > 1 && (2L - 1) >= 64
        Threads.@threads for m in -(L - 1):(L - 1)
            _wigner_fill_m_col!(Pnext, Pcur, Pprev, m, L, L1, twoLp1, LT, L1T, Lcβ,
                                i0, i1, i0p, i1p, sLm, invsL1, mpv, off_c)
        end
    else
        @inbounds for m in -(L - 1):(L - 1)
            _wigner_fill_m_col!(Pnext, Pcur, Pprev, m, L, L1, twoLp1, LT, L1T, Lcβ,
                                i0, i1, i0p, i1p, sLm, invsL1, mpv, off_c)
        end
    end
    @inbounds for m in (-L, L)
        j = m + off_c
        Tm = T(m)
        invdenm = inv(LT * sqrt(T(L1 * L1 - m * m)))
        @simd ivdep for i in i0:i1
            Pnext[i, j] = twoLp1 * (Lcβ - mpv[i] * Tm) * Pcur[i, j] * invdenm * invsL1[i]
        end
    end
    return _seed_hw_buf!(Pnext, L1, mlim_n, β, off_r, off_c)
end

function _seed_hw_buf!(Pnext::Matrix{T}, L1::Int, mlim_n::Int, β::T,
                       off_r::Int, off_c::Int) where {T}
    _seed_hw_column!(Pnext, L1, L1, β, mlim_n, L1 + off_c, off_r)
    _seed_hw_column!(Pnext, L1, -L1, β, mlim_n, -L1 + off_c, off_r)
    if mlim_n == L1
        @inbounds for m in -(L1 - 1):(L1 - 1)
            j = m + off_c
            d_pos = Pnext[m + off_r, L1 + off_c]
            d_neg = Pnext[m + off_r, -L1 + off_c]
            Pnext[L1 + off_r, j] = (iseven(L1 - m) ? one(T) : -one(T)) * d_pos
            Pnext[-L1 + off_r, j] = (iseven(L1 + m) ? one(T) : -one(T)) * d_neg
        end
    end
    return Pnext
end

function _advance_scratch(::Type{T}, nrows::Int, scratch::Nothing) where {T}
    return Vector{T}(undef, nrows), Vector{T}(undef, nrows), Vector{T}(undef, nrows)
end

function _advance_scratch(::Type{T}, nrows::Int, scratch::NTuple{3, Vector{T}}) where {T}
    sLm, invsL1, mpv = scratch
    length(sLm) >= nrows && length(invsL1) >= nrows && length(mpv) >= nrows && return scratch
    return Vector{T}(undef, nrows), Vector{T}(undef, nrows), Vector{T}(undef, nrows)
end

function _seed_hw_and_rows!(Pnext::AbstractMatrix{T}, L1::Int, mlim_n::Int, β::T) where {T}
    _seed_hw_column!(Pnext, L1, L1, β)
    _seed_hw_column!(Pnext, L1, -L1, β)
    if mlim_n == L1
        @inbounds for m in -(L1 - 1):(L1 - 1)
            jc = m + L1 + 1
            d_pos = Pnext[m + mlim_n + 1, 2L1 + 1]
            d_neg = Pnext[m + mlim_n + 1, 1]
            Pnext[L1 + mlim_n + 1, jc] = (iseven(L1 - m) ? one(T) : -one(T)) * d_pos
            Pnext[-L1 + mlim_n + 1, jc] = (iseven(L1 + m) ? one(T) : -one(T)) * d_neg
        end
    end
    return Pnext
end

function _empty_rec(::Type{T}) where {T}
    return zeros(T, 0, 0), zeros(T, 0, 0), zeros(T, 0, 0)
end

function _rec_scratch(::Type{T}, lmax::Integer, mmax::Integer) where {T}
    nr = 2min(Int(lmax), Int(mmax)) + 1
    nc = 2Int(lmax) + 1
    return zeros(T, nr, nc), zeros(T, nr, nc), zeros(T, nr, nc)
end

function wigner_thin_d_cache(::Type{T}, lmax::Integer, mmax::Integer, β::Real) where {T}
    L = Int(lmax)
    M = Int(mmax)
    βT = T(β)
    if L < 0
        r1, r2, r3 = _empty_rec(T)
        return WignerThinD{T}(L, M, βT, Matrix{T}[], r1, r2, r3)
    end
    if _thin_d_cache_nbytes(L, M, T) > _WIGNER_THIN_D_BYTES
        r1, r2, r3 = _rec_scratch(T, L, M)
        return WignerThinD{T}(L, M, βT, Matrix{T}[], r1, r2, r3)
    end
    r1, r2, r3 = _empty_rec(T)
    planes = Vector{Matrix{T}}(undef, L + 1)
    planes[1] = T[one(T);;]
    if L == 0
        return WignerThinD{T}(L, M, βT, planes, r1, r2, r3)
    end
    P1 = zeros(T, 2min(1, M) + 1, 3)
    _wigner_d_fill_l1!(P1, βT)
    planes[2] = P1
    Pprev = planes[1]
    Pcur = P1
    scratch = (Vector{T}(undef, 2min(L, M) + 1), Vector{T}(undef, 2min(L, M) + 1),
               Vector{T}(undef, 2min(L, M) + 1))
    for ℓ in 1:(L - 1)
        L1 = ℓ + 1
        Pnext = zeros(T, 2min(L1, M) + 1, 2L1 + 1)
        _wigner_d_advance!(Pnext, Pcur, Pprev, ℓ, βT, scratch)
        planes[L1 + 1] = Pnext
        Pprev, Pcur = Pcur, Pnext
    end
    return WignerThinD{T}(L, M, βT, planes, r1, r2, r3)
end

"""
    rotate_alm!(out, alm, α, β, γ, lmax, mmax, dl, dlp, work, spin, src, Δcache, dcache, transpose_d)

Partial ZYZ rotation: `out_{ℓ m'} = Σ_m D^ℓ_{m'm}(α,β,γ) alm_{ℓ m}` for `|m'| ≤ mmax`.
`work` and `src` are length `2lmax+1`. Optional `Δcache` skips Trapani. Optional
`dcache::WignerThinD` applies stored real `d(β)` in `O(L² mmax)` (β must match
construction), or streams an `ℓ`-recurrence when `planes` is empty. `transpose_d=true` is the Euclidean adjoint of a partial forward
(input `|m'|≤mmax`, output all `m`). Bang-first.
"""
rotate_alm!(out, alm, α::Real, β::Real, γ::Real, lmax::Integer, mmax::Integer,
            dl::AbstractMatrix, dlp::AbstractMatrix, work::AbstractVector) =
    rotate_alm!(out, alm, α, β, γ, lmax, mmax, dl, dlp, work, 0)

function rotate_alm!(out, alm, α::Real, β::Real, γ::Real, lmax::Integer, mmax::Integer,
                     dl::AbstractMatrix{T}, dlp::AbstractMatrix{T},
                     work::AbstractVector, spin::Integer,
                     src::Union{AbstractVector, Nothing} = nothing,
                     Δcache::Vector{<:AbstractMatrix} = Matrix{T}[],
                     dcache::Union{WignerThinD, Nothing} = nothing,
                     transpose_d::Bool = false) where {T}
    if _use_broadcast(out) || _use_broadcast(alm) || _use_broadcast(dl)
        outh = Array(out)
        almh = Array(alm)
        dlh = Array(dl)
        dlph = Array(dlp)
        workh = Array(work)
        srch = src === nothing ? similar(workh) : Array(src)
        _rotate_alm_cpu!(outh, almh, α, β, γ, lmax, mmax, dlh, dlph, workh, spin, srch,
                         Δcache, dcache, transpose_d)
        copyto!(out, outh)
        return out
    end
    srcv = src === nothing ? similar(work) : src
    return _rotate_alm_cpu!(out, alm, α, β, γ, lmax, mmax, dl, dlp, work, spin, srcv,
                            Δcache, dcache, transpose_d)
end

function _rotate_alm_cpu!(out, alm, α::Real, β::Real, γ::Real, lmax::Integer, mmax::Integer,
                          dl::AbstractMatrix{T}, dlp::AbstractMatrix{T},
                          work::AbstractVector, spin::Integer, src::AbstractVector,
                          Δcache::Vector{<:AbstractMatrix} = Matrix{T}[],
                          dcache::Union{WignerThinD, Nothing} = nothing,
                          transpose_d::Bool = false) where {T}
    if dcache !== nothing && !isempty(dcache.planes)
        return _rotate_thin_d!(out, alm, α, γ, lmax, spin, work, src, dcache, transpose_d)
    elseif dcache !== nothing && !isempty(dcache.rec1)
        return _rotate_recurrence!(out, alm, α, γ, lmax, spin, work, src, dcache, transpose_d)
    end
    off = Int(lmax) + 1
    L = 2Int(lmax) + 1
    size(dl, 1) >= L && size(dlp, 1) >= L || throw(DimensionMismatch("Wigner planes too small"))
    B = _ntrans(alm)
    CT = eltype(alm)
    s = Int(spin)
    cached = !isempty(Δcache)
    fill!(out, zero(CT))
    if !cached
        _wigner_d_halfpi_step!(dl, dlp, 0, off)
    end
    cγ = cis(-T(γ))
    cβ = cis(-T(β))
    cα = cis(-T(α))
    @inbounds for ℓ in 0:Int(lmax)
        if cached
            Δ = Δcache[ℓ + 1]
        else
            if ℓ > 0
                dl, dlp = dlp, dl
                _wigner_d_halfpi_step!(dl, dlp, ℓ, off)
            end
            Δ = view(dl, (off - ℓ):(off + ℓ), (off - ℓ):(off + ℓ))
        end
        ℓ < abs(s) && continue
        n = 2ℓ + 1
        mlim = min(ℓ, Int(mmax))
        wv = view(work, 1:n)
        sv = view(src, 1:n)
        for b in 1:B
            sv[ℓ + 1] = _rot_get(alm, ℓ, 0, lmax, b, s)
            phγ = one(CT)
            for m in 1:ℓ
                phγ *= cγ
                sv[m + ℓ + 1] = _im_pow(CT, -m) * phγ * _rot_get(alm, ℓ, m, lmax, b, s)
                sv[-m + ℓ + 1] = _im_pow(CT, m) * conj(phγ) * _rot_get(alm, ℓ, -m, lmax, b, s)
            end
            LinearAlgebra.mul!(wv, Δ, sv)
            phβ = one(CT)
            for k in 1:ℓ
                phβ *= cβ
                wv[k + ℓ + 1] *= phβ
                wv[-k + ℓ + 1] *= conj(phβ)
            end
            jc = (ℓ + 1 - mlim):(ℓ + 1 + mlim)
            ov = view(src, 1:(2mlim + 1))
            LinearAlgebra.mul!(ov, LinearAlgebra.transpose(view(Δ, :, jc)), wv)
            phα = one(CT)
            _rot_set!(out, ℓ, 0, lmax, b, ov[mlim + 1], s)
            for mp in 1:mlim
                phα *= cα
                _rot_set!(out, ℓ, mp, lmax, b, ov[mp + mlim + 1] * _im_pow(CT, mp) * phα, s)
                _rot_set!(out, ℓ, -mp, lmax, b, ov[-mp + mlim + 1] * _im_pow(CT, -mp) * conj(phα), s)
            end
        end
    end
    return out
end

"""
Apply stored `d(β)`: forward `out_{m'} = e^{-im'α} (d v)_ {m'}` with `v_m = e^{-imγ} a_m`;
`transpose_d` does `out_m = e^{-imα} (dᵀ v)_m` with `v_{m'} = e^{-im'γ} a_{m'}`.
"""
function _rotate_thin_d!(out, alm, α::Real, γ::Real, lmax::Integer, spin::Integer,
                         work::AbstractVector, src::AbstractVector,
                         dcache::WignerThinD, transpose_d::Bool)
    B = _ntrans(alm)
    CT = eltype(alm)
    s = Int(spin)
    M = dcache.mmax
    fill!(out, zero(CT))
    T = typeof(dcache.β)
    cγ = cis(-T(γ))
    cα = cis(-T(α))
    @inbounds for ℓ in 0:Int(lmax)
        ℓ < abs(s) && continue
        d = dcache.planes[ℓ + 1]
        mlim = min(ℓ, M)
        n = 2ℓ + 1
        nr = 2mlim + 1
        for b in 1:B
            if transpose_d
                sv = view(src, 1:nr)
                wv = view(work, 1:n)
                sv[mlim + 1] = _rot_get(alm, ℓ, 0, lmax, b, s)
                phγ = one(CT)
                for mp in 1:mlim
                    phγ *= cγ
                    sv[mp + mlim + 1] = phγ * _rot_get(alm, ℓ, mp, lmax, b, s)
                    sv[-mp + mlim + 1] = conj(phγ) * _rot_get(alm, ℓ, -mp, lmax, b, s)
                end
                LinearAlgebra.mul!(wv, LinearAlgebra.transpose(d), sv)
                phα = one(CT)
                _rot_set!(out, ℓ, 0, lmax, b, wv[ℓ + 1], s)
                for m in 1:ℓ
                    phα *= cα
                    _rot_set!(out, ℓ, m, lmax, b, wv[m + ℓ + 1] * phα, s)
                    _rot_set!(out, ℓ, -m, lmax, b, wv[-m + ℓ + 1] * conj(phα), s)
                end
            else
                sv = view(src, 1:n)
                ov = view(work, 1:nr)
                sv[ℓ + 1] = _rot_get(alm, ℓ, 0, lmax, b, s)
                phγ = one(CT)
                for m in 1:ℓ
                    phγ *= cγ
                    sv[m + ℓ + 1] = phγ * _rot_get(alm, ℓ, m, lmax, b, s)
                    sv[-m + ℓ + 1] = conj(phγ) * _rot_get(alm, ℓ, -m, lmax, b, s)
                end
                LinearAlgebra.mul!(ov, d, sv)
                phα = one(CT)
                _rot_set!(out, ℓ, 0, lmax, b, ov[mlim + 1], s)
                for mp in 1:mlim
                    phα *= cα
                    _rot_set!(out, ℓ, mp, lmax, b, ov[mp + mlim + 1] * phα, s)
                    _rot_set!(out, ℓ, -mp, lmax, b, ov[-mp + mlim + 1] * conj(phα), s)
                end
            end
        end
    end
    return out
end

"""
Stream `d^ℓ(β)` with the three-term `ℓ` recurrence into `dcache.rec*` (no packed
planes). Same apply as [`_rotate_thin_d!`](@ref).
"""
function _rotate_recurrence!(out, alm, α::Real, γ::Real, lmax::Integer, spin::Integer,
                             work::AbstractVector, src::AbstractVector,
                             dcache::WignerThinD{T}, transpose_d::Bool) where {T}
    L = Int(lmax)
    M = dcache.mmax
    β = dcache.β
    A, B, C = dcache.rec1, dcache.rec2, dcache.rec3
    fill!(A, zero(T))
    fill!(B, zero(T))
    fill!(C, zero(T))
    fill!(out, zero(eltype(out)))
    P0 = _thin_plane_view(A, 0, M, L)
    P0[1, 1] = one(T)
    _apply_d_plane!(out, alm, P0, 0, α, γ, lmax, spin, work, src, transpose_d)
    L == 0 && return out
    P1 = _thin_plane_view(B, 1, M, L)
    _wigner_d_fill_l1!(P1, β)
    _apply_d_plane!(out, alm, P1, 1, α, γ, lmax, spin, work, src, transpose_d)
    prev, cur, nxt = A, B, C
    nr = size(A, 1)
    scratch = (Vector{T}(undef, nr), Vector{T}(undef, nr), Vector{T}(undef, nr))
    for ℓ in 1:(L - 1)
        _wigner_d_advance_buf!(nxt, cur, prev, ℓ, M, L, β, scratch)
        _apply_d_plane!(out, alm, _thin_plane_view(nxt, ℓ + 1, M, L), ℓ + 1, α, γ, lmax,
                        spin, work, src, transpose_d)
        prev, cur, nxt = cur, nxt, prev
    end
    return out
end

function _apply_d_plane!(out, alm, d::AbstractMatrix, ℓ::Integer, α::Real, γ::Real,
                         lmax::Integer, spin::Integer, work, src, transpose_d::Bool)
    ℓ < abs(Int(spin)) && return out
    B = _ntrans(alm)
    CT = eltype(alm)
    s = Int(spin)
    T = real(CT)
    Mlim = (size(d, 1) - 1) ÷ 2
    n = 2ℓ + 1
    nr = 2Mlim + 1
    cγ = cis(-T(γ))
    cα = cis(-T(α))
    @inbounds for b in 1:B
        if transpose_d
            sv = view(src, 1:nr)
            wv = view(work, 1:n)
            sv[Mlim + 1] = _rot_get(alm, ℓ, 0, lmax, b, s)
            phγ = one(CT)
            for mp in 1:Mlim
                phγ *= cγ
                sv[mp + Mlim + 1] = phγ * _rot_get(alm, ℓ, mp, lmax, b, s)
                sv[-mp + Mlim + 1] = conj(phγ) * _rot_get(alm, ℓ, -mp, lmax, b, s)
            end
            LinearAlgebra.mul!(wv, LinearAlgebra.transpose(d), sv)
            phα = one(CT)
            _rot_set!(out, ℓ, 0, lmax, b, wv[ℓ + 1], s)
            for m in 1:ℓ
                phα *= cα
                _rot_set!(out, ℓ, m, lmax, b, wv[m + ℓ + 1] * phα, s)
                _rot_set!(out, ℓ, -m, lmax, b, wv[-m + ℓ + 1] * conj(phα), s)
            end
        else
            sv = view(src, 1:n)
            ov = view(work, 1:nr)
            sv[ℓ + 1] = _rot_get(alm, ℓ, 0, lmax, b, s)
            phγ = one(CT)
            for m in 1:ℓ
                phγ *= cγ
                sv[m + ℓ + 1] = phγ * _rot_get(alm, ℓ, m, lmax, b, s)
                sv[-m + ℓ + 1] = conj(phγ) * _rot_get(alm, ℓ, -m, lmax, b, s)
            end
            LinearAlgebra.mul!(ov, d, sv)
            phα = one(CT)
            _rot_set!(out, ℓ, 0, lmax, b, ov[Mlim + 1], s)
            for mp in 1:Mlim
                phα *= cα
                _rot_set!(out, ℓ, mp, lmax, b, ov[mp + Mlim + 1] * phα, s)
                _rot_set!(out, ℓ, -mp, lmax, b, ov[-mp + Mlim + 1] * conj(phα), s)
            end
        end
    end
    return out
end

function rotate_alm!(out, alm, α, β, γ, lmax::Integer, mmax::Integer, spin::Integer = 0)
    T = real(eltype(alm))
    L = 2Int(lmax) + 1
    dl = _zeros_like(alm, T, L, L)
    dlp = _zeros_like(alm, T, L, L)
    work = _zeros_like(alm, eltype(alm), L)
    src = _zeros_like(alm, eltype(alm), L)
    return rotate_alm!(out, alm, α, β, γ, lmax, mmax, dl, dlp, work, spin, src)
end
